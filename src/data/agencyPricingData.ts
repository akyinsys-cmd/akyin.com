export function formatInrAmount(amount: number): string {
  return `₹${Math.round(amount).toLocaleString('en-IN')}`;
}

export function formatAedAmount(amount: number): string {
  return `AED ${Math.round(amount).toLocaleString('en-US')}`;
}

/**
 * Resolves display price respecting Phase 8 International Governance:
 * - Never auto-converts INR to AED unless an administrator has explicitly enabled UAE pricing
 *   and configured either an approved AED service price or an admin-approved conversion rate.
 */
export function resolveServiceDisplayPrice(
  service: AgencyServiceItem,
  country: SupportedCountry,
  currency: SupportedCurrency,
  rules: PricingRulesConfig
): {
  label: string;
  numericValue: number | null;
  isAedConfigured: boolean;
  isCustomQuote: boolean;
} {
  if (service.isCustomQuote || service.priceInr === null) {
    return {
      label: 'Custom Quote',
      numericValue: null,
      isAedConfigured: false,
      isCustomQuote: true,
    };
  }

  const suffix = service.unitLabel || (service.billingCycle === 'monthly' ? '/month' : '');

  if (currency === 'AED' || country === 'UAE') {
    if (!rules.uaePricingEnabled) {
      return {
        label: 'AED Quote on Request',
        numericValue: null,
        isAedConfigured: false,
        isCustomQuote: true,
      };
    }

    if (rules.uaePricingMode === 'custom-list' && service.priceAed !== null && service.priceAed > 0) {
      return {
        label: `${formatAedAmount(service.priceAed)}${suffix}`,
        numericValue: service.priceAed,
        isAedConfigured: true,
        isCustomQuote: false,
      };
    }

    if (rules.uaePricingMode === 'admin-rate' && rules.aedExchangeRate && rules.aedExchangeRate > 0) {
      const aedVal = service.priceAed && service.priceAed > 0
        ? service.priceAed
        : Math.max(10, Math.round(service.priceInr / rules.aedExchangeRate));
      return {
        label: `${formatAedAmount(aedVal)}${suffix}`,
        numericValue: aedVal,
        isAedConfigured: true,
        isCustomQuote: false,
      };
    }

    return {
      label: 'AED Quote on Request',
      numericValue: null,
      isAedConfigured: false,
      isCustomQuote: true,
    };
  }

  return {
    label: `${formatInrAmount(service.priceInr)}${suffix}`,
    numericValue: service.priceInr,
    isAedConfigured: true,
    isCustomQuote: false,
  };
}

export function resolveMonthlyPackagePrice(
  pkg: MonthlyGrowthPackage,
  country: SupportedCountry,
  currency: SupportedCurrency,
  rules: PricingRulesConfig
): { label: string; numericValue: number | null; isAedConfigured: boolean } {
  if (currency === 'AED' || country === 'UAE') {
    if (!rules.uaePricingEnabled) {
      return { label: 'AED Quote on Request', numericValue: null, isAedConfigured: false };
    }
    if (rules.uaePricingMode === 'custom-list' && pkg.priceAed !== null && pkg.priceAed > 0) {
      return { label: `${formatAedAmount(pkg.priceAed)}/month`, numericValue: pkg.priceAed, isAedConfigured: true };
    }
    if (rules.uaePricingMode === 'admin-rate' && rules.aedExchangeRate && rules.aedExchangeRate > 0) {
      const aedVal = pkg.priceAed && pkg.priceAed > 0
        ? pkg.priceAed
        : Math.max(50, Math.round(pkg.priceInr / rules.aedExchangeRate));
      return { label: `${formatAedAmount(aedVal)}/month`, numericValue: aedVal, isAedConfigured: true };
    }
    return { label: 'AED Quote on Request', numericValue: null, isAedConfigured: false };
  }

  return {
    label: `${formatInrAmount(pkg.priceInr)}/month`,
    numericValue: pkg.priceInr,
    isAedConfigured: true,
  };
}
